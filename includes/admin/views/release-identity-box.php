<?php
/**
 * Release identity meta box: required identifiers and the artist link.
 *
 * @package MDS_Release_Manager
 */

declare(strict_types=1);

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}
?>
<div class="mds-meta-section">
    <?php // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_nonce_field(). ?>
	<?php echo $args['nonce_field']; ?>
	<table class="mds-meta-table">
		<tr>
			<th><label for="upc_ean"><?php esc_html_e( 'UPC/EAN *', 'mds-release-manager' ); ?></label></th>
			<td><input type="text" id="upc_ean" name="upc_ean" value="<?php echo esc_attr( $args['upc_ean'] ); ?>" required /></td>
		</tr>
		<tr>
			<th><label for="release_format"><?php esc_html_e( 'Release Format *', 'mds-release-manager' ); ?></label></th>
			<td>
				<?php if ( is_wp_error( $args['all_formats'] ) || is_wp_error( $args['release_formats'] ) ) : ?>
					<p><?php esc_html_e( 'Unable to load release formats. Please reload the page.', 'mds-release-manager' ); ?></p>
				<?php else : ?>
					<?php $can_assign_formats = current_user_can( get_taxonomy( 'release_format' )->cap->assign_terms ); ?>
					<?php if ( $args['format_conflict'] ) : ?>
						<p class="notice notice-warning inline"><?php esc_html_e( 'The existing format conflicts with legacy data. Choose the correct format to resolve it.', 'mds-release-manager' ); ?></p>
					<?php endif; ?>
					<select id="release_format" name="release_format" required <?php disabled( ! $can_assign_formats ); ?>>
						<option value=""><?php esc_html_e( 'Select a release format', 'mds-release-manager' ); ?></option>
						<?php foreach ( $args['all_formats'] as $format ) : ?>
							<?php
							if ( 0 !== (int) $format->parent || ! in_array( $format->name, MDS_RM_Release_Model::MDS_RM_FORMATS, true ) ) {
								continue;
							}
							?>
							<option value="<?php echo esc_attr( $format->term_id ); ?>" <?php selected( ! $args['format_conflict'] && 1 === count( $args['release_formats'] ) && in_array( $format->term_id, $args['release_formats'], true ) ); ?>>
								<?php echo esc_html( $format->name ); ?>
							</option>
						<?php endforeach; ?>
					</select>
				<?php endif; ?>
			</td>
		</tr>
		<tr>
			<th><label for="artist_id"><?php esc_html_e( 'Artist Profile', 'mds-release-manager' ); ?></label></th>
			<td>
				<select id="artist_id" name="artist_id">
					<?php if ( ! $args['artists_found'] ) : ?>
						<option value=""><?php esc_html_e( 'No Artists Found. Please Create One.', 'mds-release-manager' ); ?></option>
					<?php else : ?>
						<option value=""><?php esc_html_e( '-- Select Artist --', 'mds-release-manager' ); ?></option>
						<?php foreach ( $args['artists'] as $artist ) : ?>
							<?php if ( $artist['uuid'] ) : ?>
								<option value="<?php echo esc_attr( $artist['uuid'] ); ?>" <?php selected( $args['artist_id'], $artist['uuid'] ); ?>><?php echo esc_html( $artist['title'] ); ?></option>
							<?php endif; ?>
						<?php endforeach; ?>
					<?php endif; ?>
				</select>
			</td>
		</tr>
	</table>
</div>
