<?php
/**
 * Release identity meta box: required identifiers and the artist link.
 *
 * @package MDS_Release_Manager
 */

declare(strict_types=1);

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

( static function ( array $args ): void {
	?>
<div class="mds-meta-section">
	<?php // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by wp_nonce_field(). ?>
	<?php echo $args['nonce_field']; ?>
	<table class="mds-meta-table">
		<tr>
			<th><label for="upc_ean"><?php esc_html_e( 'UPC/EAN *', 'mds-release-manager' ); ?></label></th>
			<td><input type="text" id="upc_ean" name="upc_ean" value="<?php echo esc_attr( $args['upc_ean'] ); ?>" required /></td>
		</tr>
		<tr>
			<th><label for="release_type"><?php esc_html_e( 'Release Type *', 'mds-release-manager' ); ?></label></th>
			<td>
				<?php if ( is_wp_error( $args['all_formats'] ) || is_wp_error( $args['release_formats'] ) ) : ?>
					<p><?php esc_html_e( 'Unable to load release types. Please reload the page.', 'mds-release-manager' ); ?></p>
				<?php else : ?>
					<?php $can_assign_formats = current_user_can( get_taxonomy( 'release_type' )->cap->assign_terms ); ?>
					<?php if ( $args['format_conflict'] ) : ?>
						<p class="notice notice-warning inline"><?php esc_html_e( 'The existing release type conflicts with legacy data. Choose the correct release type to resolve it.', 'mds-release-manager' ); ?></p>
					<?php endif; ?>
					<select id="release_type" name="release_type" required <?php disabled( ! $can_assign_formats ); ?>>
						<option value=""><?php esc_html_e( 'Select a release type', 'mds-release-manager' ); ?></option>
						<?php foreach ( $args['all_formats'] as $format ) : ?>
							<?php
							if ( 0 !== (int) $format->parent || ! in_array( $format->name, \MDS\ReleaseManager\Core\ReleaseModel::MDS_RM_FORMATS, true ) ) {
								continue;
							}
							?>
							<option value="<?php echo esc_attr( $format->term_id ); ?>" <?php selected( ! $args['format_conflict'] && 1 === count( $args['release_formats'] ) && in_array( $format->term_id, $args['release_formats'], true ) ); ?>>
								<?php echo esc_html( $format->name ); ?>
							</option>
						<?php endforeach; ?>
					</select>
				<?php endif; ?>
			</td>
		</tr>
		<tr>
			<th><label for="mds-artist-search"><?php esc_html_e( 'Artist Profile', 'mds-release-manager' ); ?></label></th>
			<td>
				<input type="search" id="mds-artist-search" class="regular-text" autocomplete="off" aria-describedby="mds-artist-picker-status" />
				<input type="hidden" id="artist_id" name="artist_id" value="<?php echo esc_attr( $args['artist_id'] ); ?>" />
				<p id="mds-artist-selected" class="description" <?php echo '' === $args['selected_artist_title'] ? 'hidden' : ''; ?>>
					<?php
					if ( '' !== $args['selected_artist_title'] ) {
						printf(
							/* translators: %s: Selected Artist name. */
							esc_html__( 'Selected: %s', 'mds-release-manager' ),
							esc_html( $args['selected_artist_title'] )
						);
					}
					?>
				</p>
				<button type="button" class="button button-small" id="mds-clear-artist-selection"><?php esc_html_e( 'Clear Artist', 'mds-release-manager' ); ?></button>
				<div id="mds-artist-results" role="listbox" aria-label="<?php esc_attr_e( 'Artist search results', 'mds-release-manager' ); ?>"></div>
				<div id="mds-artist-pagination"></div>
				<p id="mds-artist-picker-status" class="description" aria-live="polite"><?php esc_html_e( 'Type an Artist name to search.', 'mds-release-manager' ); ?></p>
			</td>
		</tr>
	</table>
</div>
	<?php
} )( is_array( $args ?? null ) ? $args : array() );
